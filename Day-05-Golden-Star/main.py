import turtle
screen = turtle.Screen()
screen.setup(650, 580)
screen.bgcolor("#171323")
screen.title("Golden Star")
pen = turtle.Turtle()
pen.speed(0)
pen.pensize(5)
pen.color("#ffd166", "#f4a261")
pen.penup()
pen.goto(0, 150)
pen.pendown()
pen.begin_fill()
for _ in range(5):
    pen.forward(280)
    pen.right(144)
pen.end_fill()
pen.hideturtle()
turtle.done()
